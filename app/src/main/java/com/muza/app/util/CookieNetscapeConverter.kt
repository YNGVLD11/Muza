package com.muza.app.util

import android.content.Context
import android.util.Log
import android.webkit.CookieManager
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStreamWriter
import java.nio.charset.StandardCharsets

object CookieNetscapeConverter {
    private const val TAG = "CookieNetscapeConverter"
    private const val COOKIES_FILE_NAME = "cookies.txt"

    fun getCookiesFile(context: Context): File {
        return File(context.filesDir, COOKIES_FILE_NAME)
    }

    fun hasCookies(context: Context): Boolean {
        val file = getCookiesFile(context)
        return file.exists() && file.length() > 0
    }

    fun clearCookies(context: Context) {
        val file = getCookiesFile(context)
        if (file.exists()) {
            file.delete()
        }
        val cookieManager = CookieManager.getInstance()
        cookieManager.removeAllCookies(null)
        cookieManager.flush()
    }

    /**
     * Extracts cookies for YouTube and Google from android.webkit.CookieManager,
     * formats them into Netscape HTTP Cookie format, and saves to filesDir/cookies.txt.
     */
    fun saveCookiesFromCookieManager(context: Context): Boolean {
        return try {
            val cookieManager = CookieManager.getInstance()
            val targetDomains = listOf(
                "https://www.youtube.com" to ".youtube.com",
                "https://accounts.google.com" to ".google.com",
                "https://myaccount.google.com" to ".google.com"
            )

            val lines = mutableListOf<String>()
            lines.add("# Netscape HTTP Cookie File")
            lines.add("# http://curl.haxx.se/rfc/cookie_spec.html")
            lines.add("# This file was generated by Muza. Do not edit.")
            lines.add("")

            // Expiry timestamp far into the future (year 2038 or 1 year ahead)
            val expiryTimestamp = (System.currentTimeMillis() / 1000) + (365L * 24 * 3600)

            var totalCookiesFound = 0
            val processedCookies = mutableSetOf<String>()

            for ((url, domain) in targetDomains) {
                val cookieString = cookieManager.getCookie(url) ?: continue
                val cookies = cookieString.split(";")

                for (cookie in cookies) {
                    val trimmed = cookie.trim()
                    if (trimmed.isEmpty()) continue

                    val eqIndex = trimmed.indexOf('=')
                    if (eqIndex == -1) continue

                    val name = trimmed.substring(0, eqIndex).trim()
                    val value = trimmed.substring(eqIndex + 1).trim()

                    val dedupeKey = "$domain|$name"
                    if (processedCookies.contains(dedupeKey)) continue
                    processedCookies.add(dedupeKey)

                    // Format: domain flag path secure expiration name value
                    // e.g. .youtube.com TRUE / TRUE 1750000000 SID abc123xyz
                    val line = "$domain\tTRUE\t/\tTRUE\t$expiryTimestamp\t$name\t$value"
                    lines.add(line)
                    totalCookiesFound++
                }
            }

            if (totalCookiesFound == 0) {
                Log.w(TAG, "No cookies found to save")
                return false
            }

            val file = getCookiesFile(context)
            OutputStreamWriter(FileOutputStream(file), StandardCharsets.UTF_8).use { writer ->
                for (l in lines) {
                    writer.write(l)
                    writer.write("\n")
                }
            }
            Log.d(TAG, "Successfully saved $totalCookiesFound cookies to ${file.absolutePath}")
            true
        } catch (e: Exception) {
            Log.e(TAG, "Error saving cookies to Netscape format", e)
            false
        }
    }
}
